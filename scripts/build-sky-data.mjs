/**
 * Regenerates the committed sky data under src/projects/starchart/data/.
 *
 *   node scripts/build-sky-data.mjs
 *
 * The OUTPUT is committed, not the input — this script exists so the encoding is
 * reproducible and auditable, not because the build runs it. Nothing in `npm run
 * build` calls it, and it is outside both `tsconfig.app.json`'s `include` and
 * eslint's `**\/*.{ts,tsx}` glob on purpose.
 *
 * Source: ofrohn/d3-celestial `data/`, BSD-3-Clause. That data is in turn reduced
 * from Hipparcos/Tycho (stars), the IAU constellation figures, and the Milky Way
 * outlines traced for the same project. See data/README.md.
 */

import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'projects', 'starchart', 'data');

const BASE = `https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data`;

/** Faintest star kept. 8.0 is where the file ends; see the note in catalog.ts. */
const MAG_LIMIT = 8;

/** Quantisation ranges. Anything outside is clamped, so these must bracket the data. */
const MAG_MIN = -2;
const MAG_MAX = 10.75; // (MAG_MAX - MAG_MIN) / 255 == 0.05 mag per step
const BV_MIN = -0.5;
const BV_MAX = 3.05; // 0.0139 per step; the tint ramp cannot resolve finer

/**
 * Milky Way raster. 512x256 is ~0.7 deg per cell.
 *
 * The resolution is not really about detail — the source is only five nested
 * outlines, so there are only six distinct values in it. It is about having
 * enough cells to BLUR across: the raw contours read as hard terraces on the
 * plate, and MW_BLUR turns them into the continuous wash the band actually is.
 * Smooth data compresses far better than detailed data, so this costs almost
 * nothing in the generated file.
 */
const MW_W = 512;
const MW_H = 256;
/** Box-blur radius in cells, applied three times to approximate a Gaussian. */
const MW_BLUR = 5;

async function getJson(name) {
  const res = await fetch(`${BASE}/${name}`);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  return res.json();
}

function b64(buf) {
  return Buffer.from(buf).toString('base64');
}

/** Wrap the base64 blob so the generated file does not have one 300KB line. */
function wrap(s, width = 116) {
  const lines = [];
  for (let i = 0; i < s.length; i += width) lines.push(s.slice(i, i + width));
  return lines.join('\n');
}

const header = (what) =>
  `// GENERATED by scripts/build-sky-data.mjs — do not edit by hand.\n` +
  `// ${what}\n` +
  `// Source: ofrohn/d3-celestial, BSD-3-Clause. See ./README.md.\n`;

// ---------------------------------------------------------------------------
// Stars
// ---------------------------------------------------------------------------

function buildStars(starsJson, namesJson) {
  const rows = [];
  for (const f of starsJson.features) {
    const mag = f.properties.mag;
    if (!(mag <= MAG_LIMIT)) continue;
    const [ra, dec] = f.geometry.coordinates;
    const bv = Number.parseFloat(f.properties.bv);
    rows.push({
      hip: String(f.id),
      // The source uses -180..180; the runtime wants 0..360 so RA is monotonic.
      ra: ra < 0 ? ra + 360 : ra,
      dec,
      mag,
      // 52 stars carry no colour index. 0.65 is roughly solar — a neutral guess
      // beats dropping the star or defaulting it to blue.
      bv: Number.isFinite(bv) ? bv : 0.65,
    });
  }

  // Brightest first. Three things fall out of this ordering: the limiting-
  // magnitude cut becomes a prefix slice, the magnitude column becomes monotonic
  // (so it compresses to nearly nothing), and named stars land at low indices.
  rows.sort((a, b) => a.mag - b.mag);

  const n = rows.length;
  const ra = new Uint16Array(n);
  const dec = new Uint16Array(n);
  const mag = new Uint8Array(n);
  const bv = new Uint8Array(n);

  const q = (v, lo, hi, steps) =>
    Math.max(0, Math.min(steps, Math.round(((v - lo) / (hi - lo)) * steps)));

  for (let i = 0; i < n; i++) {
    const r = rows[i];
    ra[i] = q(r.ra, 0, 360, 65535);
    dec[i] = q(r.dec, -90, 90, 65535);
    mag[i] = q(r.mag, MAG_MIN, MAG_MAX, 255);
    bv[i] = q(r.bv, BV_MIN, BV_MAX, 255);
  }

  // Column-major: each column is far more self-similar than an interleaved
  // record, which is most of the gzip win.
  const buf = Buffer.alloc(n * 6);
  Buffer.from(ra.buffer).copy(buf, 0);
  Buffer.from(dec.buffer).copy(buf, n * 2);
  Buffer.from(mag.buffer).copy(buf, n * 4);
  Buffer.from(bv.buffer).copy(buf, n * 5);

  // --- names, keyed by index into the array above ---
  const nameLines = [];
  for (let i = 0; i < n; i++) {
    const rec = namesJson[rows[i].hip];
    if (!rec) continue;
    const hd = rec.hd ? rec.hd.replace(/^HD\s*/, '') : '';
    const fields = [rec.name || '', rec.bayer || '', rec.flam || '', rec.c || '', hd];
    if (fields.every((f) => f === '')) continue;
    nameLines.push(`${i}|${fields.join('|')}`);
  }

  return { n, buf, nameLines, brightest: rows[0].mag, faintest: rows[n - 1].mag };
}

// ---------------------------------------------------------------------------
// Milky Way
// ---------------------------------------------------------------------------

/**
 * Rasterise the nested outline polygons into a density map.
 *
 * Two properties of this data drive the method. The outer rings wind once around
 * the sphere (RA is periodic, and they close by wrapping the seam), so they are
 * unwrapped into a continuous RA sequence and the sampling ray is replicated at
 * +/-360. And the band is an annulus, not a disc — even-odd on a ray cast toward
 * the north pole, which is genuinely outside every ring, resolves that correctly
 * where a winding rule on the raw planar coordinates would not.
 */
function buildMilkyWay(mwJson) {
  const acc = new Uint8Array(MW_W * MW_H);

  for (const feature of mwJson.features) {
    const geom = feature.geometry;
    const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;

    // Edge list in unwrapped RA, shared across every ring of this level so that
    // even-odd sees holes (the Great Rift) as part of the same figure.
    const edges = [];
    let spanMin = Infinity;
    let spanMax = -Infinity;

    for (const poly of polys) {
      for (const ring of poly) {
        let prevRa = ring[0][0] < 0 ? ring[0][0] + 360 : ring[0][0];
        let prevDec = ring[0][1];
        spanMin = Math.min(spanMin, prevRa);
        spanMax = Math.max(spanMax, prevRa);
        for (let i = 1; i < ring.length; i++) {
          let raw = ring[i][0] < 0 ? ring[i][0] + 360 : ring[i][0];
          // Unwrap: keep each step under half a turn, letting RA run past 360.
          while (raw - prevRa > 180) raw -= 360;
          while (raw - prevRa < -180) raw += 360;
          const d = ring[i][1];
          if (raw !== prevRa) edges.push([prevRa, prevDec, raw, d]);
          prevRa = raw;
          prevDec = d;
          spanMin = Math.min(spanMin, raw);
          spanMax = Math.max(spanMax, raw);
        }
      }
    }

    for (let ix = 0; ix < MW_W; ix++) {
      const ra0 = ((ix + 0.5) / MW_W) * 360;
      const crossings = [];
      for (let k = Math.floor((spanMin - ra0) / 360); k <= Math.ceil((spanMax - ra0) / 360); k++) {
        const ray = ra0 + k * 360;
        for (const [x1, y1, x2, y2] of edges) {
          // Half-open span, so a vertex shared by two edges counts once.
          const lo = Math.min(x1, x2);
          const hi = Math.max(x1, x2);
          if (ray < lo || ray >= hi) continue;
          crossings.push(y1 + ((ray - x1) / (x2 - x1)) * (y2 - y1));
        }
      }
      if (crossings.length === 0) continue;
      crossings.sort((a, b) => a - b);

      for (let iy = 0; iy < MW_H; iy++) {
        const decCell = 90 - ((iy + 0.5) / MW_H) * 180;
        // Odd number of crossings between here and the north pole => inside.
        let above = 0;
        for (let i = crossings.length - 1; i >= 0 && crossings[i] > decCell; i--) above++;
        if (above & 1) acc[iy * MW_W + ix]++;
      }
    }
  }

  const levels = mwJson.features.length;
  let field = new Float32Array(MW_W * MW_H);
  for (let i = 0; i < acc.length; i++) field[i] = Math.min(acc[i], levels) / levels;

  // Three box blurs ~= a Gaussian. Horizontal wraps (RA is periodic) and
  // vertical clamps (Dec is not) — swapping those puts a seam down 0h or smears
  // the band across a pole, and both are very visible on a wide plate.
  for (let pass = 0; pass < 3; pass++) {
    const tmp = new Float32Array(MW_W * MW_H);
    for (let y = 0; y < MW_H; y++) {
      for (let x = 0; x < MW_W; x++) {
        let sum = 0;
        for (let k = -MW_BLUR; k <= MW_BLUR; k++) {
          sum += field[y * MW_W + (((x + k) % MW_W) + MW_W) % MW_W];
        }
        tmp[y * MW_W + x] = sum / (MW_BLUR * 2 + 1);
      }
    }
    const out2 = new Float32Array(MW_W * MW_H);
    for (let y = 0; y < MW_H; y++) {
      for (let x = 0; x < MW_W; x++) {
        let sum = 0;
        for (let k = -MW_BLUR; k <= MW_BLUR; k++) {
          const yy = Math.min(MW_H - 1, Math.max(0, y + k));
          sum += tmp[yy * MW_W + x];
        }
        out2[y * MW_W + x] = sum / (MW_BLUR * 2 + 1);
      }
    }
    field = out2;
  }

  const out = new Uint8Array(MW_W * MW_H);
  for (let i = 0; i < field.length; i++) {
    out[i] = Math.round(Math.min(1, Math.max(0, field[i])) * 255);
  }
  return { out, levels };
}

/** ASCII dump, purely so a regeneration can be eyeballed for a seam or a flip. */
function preview(map) {
  const rows = [];
  const ramp = ' .:-=+*#%@';
  for (let y = 0; y < 24; y++) {
    let line = '';
    for (let x = 0; x < 96; x++) {
      const sx = Math.floor((x / 96) * MW_W);
      const sy = Math.floor((y / 24) * MW_H);
      line += ramp[Math.min(9, Math.floor((map[sy * MW_W + sx] / 256) * 10))];
    }
    rows.push(line);
  }
  return rows.join('\n');
}

// ---------------------------------------------------------------------------
// Constellations
// ---------------------------------------------------------------------------

function buildConstellations(linesJson, namesJson) {
  const meta = new Map();
  for (const f of namesJson.features) {
    const [ra, dec] = f.geometry.coordinates;
    meta.set(f.id, {
      name: String(f.properties.name || f.id).toUpperCase(),
      gen: String(f.properties.gen || ''),
      desig: String(f.properties.desig || f.id),
      ra: ra < 0 ? ra + 360 : ra,
      dec,
      rank: Number(f.properties.rank) || 3,
    });
  }

  const out = [];
  for (const f of linesJson.features) {
    const m = meta.get(f.id);
    if (!m) continue;
    const geom = f.geometry;
    const raw = geom.type === 'MultiLineString' ? geom.coordinates : [geom.coordinates];
    // Two decimals is 36 arcsec — a tenth of a pixel at the widest field we draw.
    const paths = raw.map((line) =>
      line.flatMap(([ra, dec]) => [
        Math.round((ra < 0 ? ra + 360 : ra) * 100) / 100,
        Math.round(dec * 100) / 100,
      ]),
    );
    out.push({ id: f.id, ...m, paths });
  }
  out.sort((a, b) => a.id.localeCompare(b.id));
  return out;
}

// ---------------------------------------------------------------------------

async function main() {
  console.log('fetching d3-celestial data...');
  const [starsJson, starNamesJson, linesJson, conNamesJson, mwJson] = await Promise.all([
    getJson('stars.8.json'),
    getJson('starnames.json'),
    getJson('constellations.lines.json'),
    getJson('constellations.json'),
    getJson('milkyway.json'),
  ]);

  mkdirSync(OUT, { recursive: true });

  const stars = buildStars(starsJson, starNamesJson);
  console.log(
    `stars: ${stars.n} (mag ${stars.brightest} .. ${stars.faintest}), ` +
      `${(stars.buf.length / 1024).toFixed(0)} KiB packed, ${stars.nameLines.length} named`,
  );

  writeFileSync(
    join(OUT, 'stars.gen.ts'),
    header(
      `${stars.n} stars to magnitude ${MAG_LIMIT}, brightest first. Column-major: ` +
        `RA u16 | Dec u16 | mag u8 | B-V u8.`,
    ) +
      `\nexport const STAR_COUNT = ${stars.n};\n` +
      `export const MAG_MIN = ${MAG_MIN};\n` +
      `export const MAG_MAX = ${MAG_MAX};\n` +
      `export const BV_MIN = ${BV_MIN};\n` +
      `export const BV_MAX = ${BV_MAX};\n\n` +
      `export const STAR_DATA_B64 = \`
${wrap(b64(stars.buf))}\`;
`,
  );

  writeFileSync(
    join(OUT, 'starNames.gen.ts'),
    header(
      `Designations for the ${stars.nameLines.length} catalogued stars that carry one.\n` +
        `// One record per line: starIndex|proper|bayer|flamsteed|constellation|hd`,
    ) + `\nexport const STAR_NAMES = \`\n${stars.nameLines.join('\n')}\`;\n`,
  );

  const mw = buildMilkyWay(mwJson);
  console.log(`milky way: ${MW_W}x${MW_H}, ${mw.levels} contour levels`);
  console.log(preview(mw.out));

  writeFileSync(
    join(OUT, 'milkyway.gen.ts'),
    header(
      `Milky Way surface brightness, ${mw.levels} nested outline levels rasterised to\n` +
        `// a ${MW_W}x${MW_H} equirectangular map. Row 0 is Dec +90, column 0 is RA 0h.`,
    ) +
      `\nexport const MW_WIDTH = ${MW_W};\n` +
      `export const MW_HEIGHT = ${MW_H};\n\n` +
      `export const MW_DATA_B64 = \`
${wrap(b64(mw.out))}\`;
`,
  );

  const cons = buildConstellations(linesJson, conNamesJson);
  const segs = cons.reduce((a, c) => a + c.paths.length, 0);
  console.log(`constellations: ${cons.length} figures, ${segs} polylines`);

  writeFileSync(
    join(OUT, 'constellations.gen.ts'),
    header(
      `The ${cons.length} IAU constellation figures: line vertices in RA/Dec degrees,\n` +
        `// plus the name, Latin genitive and label anchor for each.`,
    ) +
      `\nexport interface ConstellationRecord {\n` +
      `  id: string;\n  name: string;\n  gen: string;\n  desig: string;\n` +
      `  ra: number;\n  dec: number;\n  rank: number;\n` +
      `  /** Flat [ra, dec, ra, dec, ...] per polyline. */\n  paths: number[][];\n}\n\n` +
      `export const CONSTELLATIONS: ConstellationRecord[] = ${JSON.stringify(cons)};\n`,
  );

  writeFileSync(
    join(OUT, 'README.md'),
    `# Sky data\n\n` +
      `Generated by \`scripts/build-sky-data.mjs\`. Do not edit the \`*.gen.ts\` files.\n\n` +
      `Reduced from [ofrohn/d3-celestial](https://github.com/ofrohn/d3-celestial) \`data/\`,\n` +
      `which is BSD-3-Clause. That data derives from the Hipparcos and Tycho catalogues,\n` +
      `the IAU constellation figures, and the Milky Way outlines traced for that project.\n\n` +
      `| file | contents |\n| --- | --- |\n` +
      `| \`stars.gen.ts\` | ${stars.n} stars to mag ${MAG_LIMIT}, 6 bytes each |\n` +
      `| \`starNames.gen.ts\` | ${stars.nameLines.length} designations |\n` +
      `| \`constellations.gen.ts\` | ${cons.length} figures |\n` +
      `| \`milkyway.gen.ts\` | ${MW_W}x${MW_H} brightness map |\n\n` +
      `Positions are J2000 equatorial, RA 0..360 degrees. Proper motion is not applied:\n` +
      `over the centuries the plate furniture implies it is well under a pixel.\n`,
  );

  console.log(`\nwrote ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
